// npm i jspdf jspdf-autotable
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

const COLLEGE_NAME = "LabSync | Computer Engineering";

export const exportPdf = ({ title, rangeLabel, columns, rows, summary = [], filename, generatedBy = "LabSync" }) => {
  const doc = new jsPDF({
    orientation: columns.length > 6 ? "landscape" : "portrait",
    unit: "pt",
    format: "a4",
  });

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.setTextColor(31, 42, 36);
  doc.text(COLLEGE_NAME, 40, 44);
  doc.setFontSize(12);
  doc.text(title, 40, 64);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(90);
  doc.text(`Period: ${rangeLabel}`, 40, 80);
  doc.text(`Generated by ${generatedBy} on ${new Date().toLocaleString("en-GB")}`, 40, 93);

  let startY = 108;
  if (summary.length) {
    doc.setTextColor(31, 42, 36);
    doc.text(summary.map((s) => `${s.label}: ${s.value}`).join("    |    "), 40, 112);
    startY = 126;
  }

  autoTable(doc, {
    startY,
    head: [columns.map((c) => c.label)],
    body: rows.map((r) => columns.map((c) => String(r[c.key] ?? ""))),
    styles: { fontSize: 8, cellPadding: 4 },
    headStyles: { fillColor: [31, 42, 36] },
    alternateRowStyles: { fillColor: [248, 249, 247] },
    margin: { left: 40, right: 40 },
  });

  const pages = doc.getNumberOfPages();
  const { width, height } = doc.internal.pageSize;
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(120);
    doc.text(`Page ${i} of ${pages}`, width - 40, height - 20, { align: "right" });
  }

  doc.save(filename);
};
